// Course definitions.
//
// Each hole is an ASCII tile map. Row 0 is the far side of the screen (north),
// columns run west -> east. One character = one 1x1 tile.
//
//   ' '  void (off course)      '.'  grass
//   'S'  tee (start)            'O'  cup
//   's'  sand (slow)            '~'  water (penalty stroke)
//   'o'  bumper post            '+'  spinning bar (needs a 3x3 open area)
//   '>' '<' '^' 'v'  slope; the arrow points DOWNHILL
//   'i'  ice (almost no friction)
//   '→' '←' '↑' '↓'  boost pad; pushes the ball along the arrow
//   '@'  portal entrance        '&'  portal exit (one pair per hole)
//   Water ('~') is drawn as lava on the volcano course; it plays the same.
//
// `heights` (optional) gives each tile's elevation level as a digit. For a slope
// tile the digit is the level of its LOW side; its high side is one level up.
// Edges between tiles whose surfaces do not meet automatically get a wall.

